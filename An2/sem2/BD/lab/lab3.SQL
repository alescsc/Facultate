SELECT NUME, FID, ANSTUD FROM STUDENT;

SELECT NUME FROM STUDENT WHERE NUME LIKE '%u %';

SELECT NUME FROM STUDENT WHERE SUBSTR(NUME, INSTR(NUME, ' ') - 1, 1) = 'u';

SELECT NUME FROM STUDENT WHERE LENGTH(SUBSTR(NUME, 1, INSTR(NUME, ' ') - 1)) >= 7;

SELECT NUME, (extract(YEAR FROM SYSDATE) - extract(YEAR FROM DATAN)), DATAN FROM STUDENT WHERE extract(YEAR FROM SYSDATE) - extract(YEAR FROM DATAN) = 19 OR extract(YEAR FROM SYSDATE) - extract(YEAR FROM DATAN) = 20;

SELECT NUME, extract(MONTH FROM DATAN) FROM STUDENT WHERE extract(MONTH FROM SYSDATE) = extract(MONTH FROM DATAN);

SELECT NUME, BURSA FROM STUDENT WHERE BURSA IS NULL;

SELECT NUME, BURSA FROM STUDENT WHERE BURSA = 0 OR BURSA IS NULL;

SELECT NUME, ANSTUD, NVL(CNP, 'CNP Necompletat') FROM STUDENT WHERE ANSTUD = 2 ORDER BY DATAN DESC;

SELECT NUME, CNP, CASE WHEN SUBSTR(CNP, 1, 1) = '1' OR SUBSTR(CNP, 1, 1) = '5' THEN 'baieti' WHEN SUBSTR(CNP, 1, 1) = '2' OR SUBSTR(CNP, 1, 1) = '6' THEN 'fete' END AS GRUP FROM STUDENT ORDER BY GRUP, NUME;